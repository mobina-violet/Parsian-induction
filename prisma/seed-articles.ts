async function main() {
  for (const article of articles) {
    await prisma.article.upsert({
      where: { slug: article.slug },
      update: article,
      create: article,
    });
  }

  console.log(`✅ ${articles.length} مقاله با موفقیت seed شد.`);
}

main()
  .catch((e) => {
    console.error("❌ خطا در اجرای seed مقالات:", e);
    process.exit(1);
  })
  .finally(() => prisma.$disconnect());